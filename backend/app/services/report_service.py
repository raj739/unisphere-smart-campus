from __future__ import annotations

from io import BytesIO
from datetime import datetime, timezone
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Font, Alignment
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


class ReportService:

    @staticmethod
    def _safe(value: Any) -> str:
        if value is None:
            return ""
        return str(value)

    @classmethod
    def build_pdf(
        cls,
        title: str,
        rows: list[dict[str, Any]],
        metadata: dict[str, Any] | None = None,
    ) -> bytes:

        buffer = BytesIO()

        document = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36,
        )

        styles = getSampleStyleSheet()

        elements = []

        elements.append(
            Paragraph(
                cls._safe(title),
                styles["Title"],
            )
        )

        elements.append(
            Paragraph(
                "UniSphere University Digital Platform",
                styles["Normal"],
            )
        )

        elements.append(Spacer(1, 12))

        if metadata:

            for key, value in metadata.items():

                elements.append(
                    Paragraph(
                        f"<b>{cls._safe(key)}:</b> "
                        f"{cls._safe(value)}",
                        styles["Normal"],
                    )
                )

            elements.append(Spacer(1, 12))

        if rows:

            headers = list(rows[0].keys())

            data = [
                [cls._safe(header) for header in headers]
            ]

            for row in rows:

                data.append(
                    [
                        cls._safe(row.get(header))
                        for header in headers
                    ]
                )

            table = Table(
                data,
                repeatRows=1,
            )

            table.setStyle(
                TableStyle(
                    [
                        (
                            "BACKGROUND",
                            (0, 0),
                            (-1, 0),
                            colors.HexColor("#1F2937"),
                        ),
                        (
                            "TEXTCOLOR",
                            (0, 0),
                            (-1, 0),
                            colors.white,
                        ),
                        (
                            "FONTNAME",
                            (0, 0),
                            (-1, 0),
                            "Helvetica-Bold",
                        ),
                        (
                            "GRID",
                            (0, 0),
                            (-1, -1),
                            0.5,
                            colors.grey,
                        ),
                        (
                            "ALIGN",
                            (0, 0),
                            (-1, -1),
                            "LEFT",
                        ),
                        (
                            "VALIGN",
                            (0, 0),
                            (-1, -1),
                            "MIDDLE",
                        ),
                    ]
                )
            )

            elements.append(table)

        elements.append(Spacer(1, 20))

        elements.append(
            Paragraph(
                "Generated by UniSphere",
                styles["Normal"],
            )
        )

        document.build(elements)

        return buffer.getvalue()

    @classmethod
    def build_excel(
        cls,
        title: str,
        rows: list[dict[str, Any]],
        metadata: dict[str, Any] | None = None,
    ) -> bytes:

        workbook = Workbook()

        sheet = workbook.active
        sheet.title = "Report"

        sheet["A1"] = title
        sheet["A1"].font = Font(
            bold=True,
            size=16,
        )

        current_row = 3

        if metadata:

            for key, value in metadata.items():

                sheet.cell(
                    current_row,
                    1,
                    cls._safe(key),
                )

                sheet.cell(
                    current_row,
                    2,
                    cls._safe(value),
                )

                current_row += 1

            current_row += 1

        if rows:

            headers = list(rows[0].keys())

            for column, header in enumerate(headers, 1):

                cell = sheet.cell(
                    current_row,
                    column,
                    cls._safe(header),
                )

                cell.font = Font(
                    bold=True,
                )

                cell.alignment = Alignment(
                    horizontal="center",
                )

            current_row += 1

            for row in rows:

                for column, header in enumerate(headers, 1):

                    sheet.cell(
                        current_row,
                        column,
                        cls._safe(row.get(header)),
                    )

                current_row += 1

            for column in range(
                1,
                len(headers) + 1,
            ):
                sheet.column_dimensions[
                    chr(64 + min(column, 26))
                ].width = 22

        buffer = BytesIO()

        workbook.save(buffer)

        return buffer.getvalue()

    @classmethod
    def student_summary(
        cls,
        student: Any,
    ) -> list[dict[str, Any]]:

        return [
            {
                "Field": "Name",
                "Value": cls._safe(
                    getattr(student, "name", "")
                ),
            },
            {
                "Field": "University ID",
                "Value": cls._safe(
                    getattr(student, "uni_id", "")
                ),
            },
            {
                "Field": "Enrollment Number",
                "Value": cls._safe(
                    getattr(student, "enrollment_number", "")
                ),
            },
        ]

    @staticmethod
    def generated_at() -> str:
        return datetime.now(
            timezone.utc
        ).isoformat()